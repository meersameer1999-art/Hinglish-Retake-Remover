"""Generate a clean, safe story.js automatically from the cleaned transcript.

No manual scene planning: pick up to five strong beats (numbers, lesson/step words, or the
longest spoken chunks), keep each short, and put simple cards over the footage. Everything
outside the beats stays as plain A-roll. Works with the warm-canvas style.

Usage:
  python auto_story.py WORK [--style warm-canvas] [--max-beats 5]
"""
import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import die  # noqa: E402
from transcribe import write_txt  # noqa: E402

# Small Whisper often misspells Hinglish/Hindi words. Fix the known ones so the on-screen
# cards and the saved script are clean. Keys are punctuation-stripped tokens.
CORRECTIONS = {
    "लेसर": "लेसन", "नमब": "नंबर", "नमरे": "नंबर", "तारगेट": "टारगेट",
    "एन्तिटार": "एन्टिटी", "एन्र्जी": "एनर्जी", "पजा": "पैज़", "गुरुब": "गुरु",
    "क्रेटिबलीटी": "क्रेडिबिलिटी", "बडाव": "बढ़ाव", "टेरेटेरी": "टेरिटरी",
    "अन्ट्रस्ट्फ्री": "अनट्रस्टेड", "नीष": "नीच",
    "ज़ा": "ज़्यादा", "कुन": "कौन", "श्टर्टीजी": "स्ट्रैटेजी", "श्टर्टिजी": "स्ट्रैटेजी",
    "सी": "सी", "अमे": "आप", "ame": "आप", "chikni": "चाहिए", "chahi": "चाहिए",
}

KEY = re.compile(
    r"\d|लेसन|नम्बर|नंबर|शेर|टार्गेट|गुरु|स्ट्रैटेजी|क्रेटिबिल|टेरिटरी|बिजनिस|"
    r"lesson|number|step|tip|rule|target|strategy|business", re.I)
STOP = {"that", "this", "with", "have", "आप", "हैं", "है", "से", "के", "की", "और",
        "तो", "जो", "कि", "एक", "बात", "सुनो", "matlab", "toh", "na"}


def token(s):
    s = re.sub(r"[^\w\u0900-\u097F ]", "", str(s)).strip()
    return CORRECTIONS.get(s, s)


def fix_script(work, path, tr):
    """Write the cleaned words back to transcript.json/txt so the saved script matches the cards."""
    fixed = 0
    for w in tr.get("words", []):
        old = w.get("w", "")
        bare = re.sub(r"[^\w\u0900-\u097F ]", "", str(old)).strip()
        new = CORRECTIONS.get(bare)
        if new and new != old:
            w["w"] = new
            fixed += 1
    json.dump(tr, open(path, "w", encoding="utf-8"), ensure_ascii=False, indent=0)
    txt = os.path.join(work, "transcript_edited.txt")
    if os.path.exists(txt):
        write_txt(txt, tr.get("words", []), float(tr.get("duration") or 0),
                  "Cleaned script (speech-to-text of the FINAL CLEANED audio)",
                  note="Times are seconds in cut.mp4 / final.mp4.")
    return fixed


def split_segments(words, gap=1.2):
    out, cur = [], []
    for w in words:
        if cur and w["s"] - cur[-1]["e"] > gap:
            out.append(cur)
            cur = []
        cur.append(w)
    if cur:
        out.append(cur)
    return out


def pick_beats(words, duration, max_beats=5):
    scored = []
    for seg in split_segments(words):
        length = seg[-1]["e"] - seg[0]["s"]
        if length < 2.5:
            continue
        text = " ".join(token(w["w"]) for w in seg)
        score = len(KEY.findall(text)) * 2 + min(3.0, length / 8) + (0.5 if any(c.isdigit() for c in text) else 0)
        scored.append((score, seg))
    scored.sort(key=lambda x: -x[0])
    beats = []
    for _, seg in scored[:max_beats]:
        items = [token(w["w"]) for w in seg]
        items = [x for x in items if len(x) > 2 and x.lower() not in STOP]
        items = [x for i, x in enumerate(items) if i == 0 or x != items[i - 1]][:3]
        while len(items) < 2:
            items.append("•")
        t0 = round(seg[0]["s"], 2)
        t1 = round(min(seg[-1]["e"], t0 + 6.5, duration), 2)
        if t1 - t0 < 2.0:
            continue
        beats.append({"t": t0, "end": t1, "title": " ".join(items[:2])[:30],
                      "items": [x[:18] for x in items]})
    beats.sort(key=lambda b: b["t"])
    merged = []
    for b in beats:
        if merged and b["t"] < merged[-1]["end"] + 0.3:
            merged[-1]["end"] = max(merged[-1]["end"], b["end"])
        else:
            merged.append(b)
    return merged


def make_js(beats, duration):
    spans = [[b["t"], b["end"]] for b in beats]
    return (
        "// Auto-generated by auto_story.py. Safe generic cards; plain footage elsewhere.\n"
        "const BEATS = " + json.dumps(beats, ensure_ascii=False) + ";\n"
        + """
function autoDraw(c, t) {
  for (const b of BEATS) {
    if (t < b.t || t >= b.end) continue;
    canvasBG(c); pip(c, t);
    titleChip(c, [[b.title, C.ink]], t, b.t, b.end);
    c.save(); enter(c, t, b.t, 0.4);
    const tint = [C.skyTint, C.purpleTint, C.greenTint];
    const col  = [C.skyDeep, C.purple, C.greenDeep];
    b.items.forEach((s, i) => {
      const t0 = b.t + 0.35 + i * 0.4;
      if (t < t0) return;
      c.save();
      c.globalAlpha *= outC(span(t, t0, t0 + 0.45));
      tag(c, 70, 240 + i * 76, s, tint[i % 3], col[i % 3], 26);
      c.restore();
    });
    c.restore();
    return;
  }
}
function autoScore(k) {}
"""
        + "var EDIT = { D: " + json.dumps(round(float(duration), 3))
        + ", SPANS: " + json.dumps(spans)
        + ", draw: autoDraw, score: autoScore };\n"
    )


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("work")
    ap.add_argument("--style", default="warm-canvas")
    ap.add_argument("--max-beats", type=int, default=5)
    ap.add_argument("--no-fix-script", action="store_true", help="keep the raw STT words in the saved script")
    a = ap.parse_args()
    work = os.path.abspath(a.work)
    path = os.path.join(work, "transcript_edited.json")
    if not os.path.exists(path):
        die(f"transcript_edited.json not found in {work}. Run speech-to-text on the final audio first.")
    tr = json.load(open(path, encoding="utf-8"))
    duration = float(tr.get("duration") or 0)
    if duration <= 0:
        die("transcript_edited.json has no duration")
    fixed = 0 if a.no_fix_script else fix_script(work, path, tr)
    beats = pick_beats(tr.get("words", []), duration, a.max_beats)
    story = os.path.join(work, "story.js")
    open(story, "w", encoding="utf-8").write(make_js(beats, duration))
    print(json.dumps({"story": story, "duration": round(duration, 2), "words_fixed": fixed,
                      "beats": beats, "note": "Edit story.js any time, then just run render.py WORK."},
                     indent=1, ensure_ascii=False))


if __name__ == "__main__":
    main()
